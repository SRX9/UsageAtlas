/** Spellings a product may be listed under, most specific first. */
function candidates(name) {
  const words = name
    .replace(/\b(cli|desktop|app|cloud|labs|studio|ai)\b/giu, " ")
    .trim();
  return [...new Set([compact(name), compact(words), compact(name.replace(/\s+/gu, ""))])].filter(Boolean);
}

const matches = new Map();
for (const name of [...names, ...aliases]) {
  const key = compact(name);
  const manual = BRAND_ALIASES[key];
  const hit = (manual && modules.includes(manual) ? manual : null)
    ?? candidates(name).map((candidate) => byCompact.get(candidate)).find(Boolean);
  if (hit) matches.set(key, hit);
}

const usedModules = [...new Set(matches.values())].sort();
const imports = usedModules
  .map((module, index) => `import Icon${index} from "@lobehub/icons/es/${module}/components/Mono.js";`)
  .join("\n");
const moduleIndex = new Map(usedModules.map((module, index) => [module, `Icon${index}`]));
const entries = [...matches.entries()]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([key, module]) => `  ${JSON.stringify(key)}: ${moduleIndex.get(module)},`)
  .join("\n");

writeFileSync(target, `/**
 * Generated by tooling/generate-provider-icons.mjs. Do not edit by hand.
 *
 * ${matches.size} catalog spellings across ${usedModules.length} brand marks from @lobehub/icons.
 * Keys are catalog names with punctuation and case removed.
 */
import type { ComponentType } from "react";
${imports}

type ProviderIcon = ComponentType<{ size?: number; className?: string }>;

export const PROVIDER_ICONS: Record<string, ProviderIcon> = {
${entries}
};
`);

