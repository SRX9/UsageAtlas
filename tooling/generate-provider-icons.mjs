/**
 * Builds the renderer's provider-icon registry from @lobehub/icons.
 *
 * The catalog is the source of truth for which tools exist; this script finds a
 * brand mark for each name (and alias) that has one, so the Providers screen is
 * a real logo wall instead of a field of initials. Only matched modules are
 * imported, which keeps the bundle from carrying all 321 icons.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const catalogFile = path.join(root, "apps/desktop/src/engine/discovery/catalog.ts");
const iconRoot = path.join(root, "apps/desktop/node_modules/@lobehub/icons/es");
const target = path.join(root, "apps/desktop/src/renderer/provider-icons.tsx");

const compact = (value) => value.trim().toLowerCase().replace(/[^a-z0-9]+/g, "");

const catalog = readFileSync(catalogFile, "utf8");
const names = [...catalog.matchAll(/name:\s*"([^"]+)"/gu)].map((match) => match[1]);
const aliases = [...catalog.matchAll(/aliases:\s*\[([^\]]+)\]/gu)].flatMap((match) =>
  [...match[1].matchAll(/"([^"]+)"/gu)].map((alias) => alias[1])
);

const modules = readdirSync(iconRoot).filter((directory) =>
  existsSync(path.join(iconRoot, directory, "components/Mono.js"))
);
const byCompact = new Map(modules.map((module) => [compact(module), module]));

